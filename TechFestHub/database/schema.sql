CREATE TABLE USERS (
    USER_ID NUMBER PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'STUDENT' NOT NULL,
    DEPARTMENT VARCHAR2(100),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('STUDENT', 'ADMIN'))
);

CREATE SEQUENCE USERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER USERS_BI_TRG
BEFORE INSERT ON USERS
FOR EACH ROW
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        SELECT USERS_SEQ.NEXTVAL INTO :NEW.USER_ID FROM DUAL;
    END IF;
END;
/

CREATE TABLE EVENTS (
    EVENT_ID NUMBER PRIMARY KEY,
    EVENT_NAME VARCHAR2(150) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    DESCRIPTION CLOB,
    EVENT_DATE TIMESTAMP NOT NULL,
    VENUE VARCHAR2(150) NOT NULL,
    REGISTRATION_FEE NUMBER(10,2) DEFAULT 0 NOT NULL,
    MAX_PARTICIPANTS NUMBER,
    REGISTRATION_DEADLINE TIMESTAMP,
    STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    CONSTRAINT CHK_EVENTS_STATUS CHECK (STATUS IN ('OPEN', 'CLOSED', 'COMPLETED')),
    CONSTRAINT CHK_EVENTS_FEE CHECK (REGISTRATION_FEE >= 0),
    CONSTRAINT CHK_EVENTS_CAPACITY CHECK (MAX_PARTICIPANTS IS NULL OR MAX_PARTICIPANTS > 0)
);

CREATE SEQUENCE EVENTS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER EVENTS_BI_TRG
BEFORE INSERT ON EVENTS
FOR EACH ROW
BEGIN
    IF :NEW.EVENT_ID IS NULL THEN
        SELECT EVENTS_SEQ.NEXTVAL INTO :NEW.EVENT_ID FROM DUAL;
    END IF;
END;
/

CREATE TABLE REGISTRATIONS (
    REGISTRATION_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    EVENT_ID NUMBER NOT NULL,
    REGISTERED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
    CONSTRAINT FK_REG_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_REG_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENTS(EVENT_ID),
    CONSTRAINT UQ_USER_EVENT UNIQUE (USER_ID, EVENT_ID),
    CONSTRAINT CHK_REG_STATUS CHECK (STATUS IN ('CONFIRMED', 'CANCELLED'))
);

CREATE SEQUENCE REGISTRATIONS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER REGISTRATIONS_BI_TRG
BEFORE INSERT ON REGISTRATIONS
FOR EACH ROW
BEGIN
    IF :NEW.REGISTRATION_ID IS NULL THEN
        SELECT REGISTRATIONS_SEQ.NEXTVAL INTO :NEW.REGISTRATION_ID FROM DUAL;
    END IF;
END;
/
